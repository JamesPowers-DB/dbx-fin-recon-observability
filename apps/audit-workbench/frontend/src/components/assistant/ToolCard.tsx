// One tool call by the investigator agent: what it asked, what came back, and
// the SQL it ran, so every number in the answer can be traced.
import React, { useState } from "react";
import type { Row } from "../../types";
import { CodeBlock, Mono, RowsTable, monoCaption, linkBtn } from "../ui";
import { Icon } from "../Icon";

export interface ToolCall {
  id: string;
  name: string;
  args: Record<string, unknown>;
  done: boolean;
  ok?: boolean;
  summary?: string;
  sql?: string[] | string | null;
  preview?: Row[];
  extra?: Record<string, unknown>;
}

export const TOOL_LABEL: Record<string, string> = {
  close_status: "Close status", checklist_status: "Checklist status", list_exceptions: "List exceptions",
  get_exception: "Get exception", get_source_records: "Source records", get_evidence: "Evidence",
  module_summary: "Module summary", save_working_paper: "Save working paper", escalate_to_owner: "Escalate to owner (simulated)",
  ask_genie: "Ask Genie",
};

export function argsSummary(args: Record<string, unknown>): string {
  const parts = Object.entries(args ?? {}).filter(([, v]) => v !== undefined && v !== null && v !== "").map(([k, v]) => {
    let s = typeof v === "string" ? v : JSON.stringify(v);
    if (k === "exception_id" && typeof v === "string") s = v.slice(0, 10);
    if (s.length > 60) s = `${s.slice(0, 60)}…`;
    return `${k}=${s}`;
  });
  return parts.join("  ") || "no arguments";
}

function sqlList(sql: ToolCall["sql"]): string[] {
  if (!sql) return [];
  return (Array.isArray(sql) ? sql : [sql]).filter((s) => typeof s === "string" && s.trim()) as string[];
}

export function ToolCard({ t }: { t: ToolCall }) {
  const [open, setOpen] = useState(false);
  const sql = sqlList(t.sql);
  const color = !t.done ? "var(--db-lava-600)" : t.ok === false ? "var(--danger)" : "var(--db-navy-400)";
  const extra = t.extra ?? {};
  const action = t.name === "escalate_to_owner" || t.name === "save_working_paper";
  return (
    <div style={{ border: `1px solid ${color}`, borderRadius: "var(--radius-md)", background: "var(--bg-canvas)", overflow: "hidden" }}>
      <button onClick={() => setOpen(!open)}
              style={{ width: "100%", display: "flex", gap: 10, alignItems: "center", padding: "8px 12px", background: "none",
                       border: "none", cursor: "pointer", textAlign: "left", fontFamily: "var(--font-sans)" }}>
        <span style={{ width: 8, height: 8, borderRadius: "50%", background: color, flexShrink: 0,
                       animation: !t.done ? "home-pulse 1.4s ease-in-out infinite" : undefined }} />
        <Icon name={action ? "send" : t.name === "ask_genie" ? "spark" : "data"} size={14} color="var(--fg-2)" />
        <span style={{ fontSize: "var(--fs-body-sm)", fontWeight: 600 }}>{TOOL_LABEL[t.name] ?? t.name}</span>
        <Mono dim style={{ flex: 1, minWidth: 0, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>{argsSummary(t.args)}</Mono>
        <Mono style={{ color: t.ok === false ? "var(--danger)" : "var(--fg-2)", whiteSpace: "nowrap" }}>
          {t.done ? t.summary ?? "done" : "running…"}
        </Mono>
        <Icon name={open ? "chev_d" : "chev_r"} size={14} color="var(--fg-3)" />
      </button>
      {open && (
        <div style={{ padding: "4px 12px 12px", display: "flex", flexDirection: "column", gap: 10, borderTop: "1px solid var(--border)" }}>
          {typeof extra.answer === "string" && extra.answer && (
            <div style={{ fontSize: "var(--fs-body-sm)" }}><span style={{ ...monoCaption, textTransform: "uppercase" }}>Genie: </span>{extra.answer}</div>
          )}
          {extra.ticket != null && (
            <div style={{ fontSize: "var(--fs-body-sm)" }}>
              Simulated ticket <Mono>{String(extra.ticket)}</Mono> routed to {String(extra.routed_to ?? "")}. No message was sent.
            </div>
          )}
          {t.preview && t.preview.length > 0 && <RowsTable rows={t.preview} maxHeight={220} />}
          {sql.map((s, i) => <CodeBlock key={i} code={s.trim()} label={t.name === "ask_genie" ? "SQL generated by Genie" : "SQL run by the tool"} maxHeight={220} />)}
          {!sql.length && !(t.preview && t.preview.length) && <span style={monoCaption}>No SQL recorded for this call.</span>}
        </div>
      )}
    </div>
  );
}

export function ThinkingLine({ text }: { text: string }) {
  return (
    <div style={{ display: "flex", gap: 8, alignItems: "center", ...monoCaption }}>
      <span style={{ width: 8, height: 8, borderRadius: "50%", background: "var(--db-lava-600)", animation: "home-pulse 1.4s ease-in-out infinite" }} />
      {text}
    </div>
  );
}

export function ToggleLink({ on, onClick, children }: { on: boolean; onClick: () => void; children: React.ReactNode }) {
  return <button onClick={onClick} style={{ ...linkBtn, fontWeight: on ? 700 : 400 }}>{children}</button>;
}
